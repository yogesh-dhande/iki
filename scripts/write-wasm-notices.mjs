// Cargo's machine-readable build output identifies the libraries compiled for
// the parser's Wasm target and the exact registry sources actually used.
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, sep } from "node:path";
import { fileURLToPath, URL } from "node:url";

const root = new URL("../", import.meta.url);
const out = fileURLToPath(new URL("web/packages/science/dist/licenses/", root));
const notices = new Map();
const target = "wasm32-unknown-unknown";
const artifacts = readFileSync(0, "utf8")
  .trim()
  .split("\n")
  .map((line) => JSON.parse(line));
if (
  !artifacts.some(
    (a) =>
      a.reason === "compiler-artifact" &&
      a.target.name === "iki_wasm" &&
      a.filenames.some((f) => f.endsWith(".wasm")),
  )
) {
  throw new Error("Wasm parser build is missing from the Cargo artifact list");
}
for (const artifact of artifacts) {
  if (artifact.reason !== "compiler-artifact" || artifact.target.name === "iki_wasm") continue;
  if (
    !artifact.filenames.some((file) => file.endsWith(".rlib") && file.split(sep).includes(target))
  )
    continue;
  const id = artifact.package_id;
  if (!id.startsWith("registry+") || !id.includes("#"))
    throw new Error("Unknown dependency source: " + id);
  const label = id.slice(id.lastIndexOf("#") + 1);
  const dir = dirname(artifact.manifest_path);
  const files = readdirSync(dir, { withFileTypes: true })
    .filter(
      (f) =>
        f.isFile() &&
        /^(?:licen[sc]es?|copying|unlicense|copyright|notice)(?:[.-].*)?$/i.test(f.name),
    )
    .map((f) => f.name)
    .sort();
  const texts = files.map((name) => name + "\n\n" + readFileSync(join(dir, name), "utf8"));
  if (!texts.length && label === "cel@0.15.0") {
    // This registry archive omits its workspace license. Its .cargo_vcs_info.json
    // identifies the exact upstream revision containing the retained notice.
    const sha = JSON.parse(readFileSync(join(dir, ".cargo_vcs_info.json"), "utf8")).git.sha1;
    if (sha !== "57b2a7e9b835425be0a7320e6bc0461380843f2d")
      throw new Error("Unexpected CEL source revision");
    texts.push(
      "https://github.com/cel-rust/cel-rust/blob/" +
        sha +
        "/LICENSE\n\n" +
        readFileSync(new URL("web/packages/science/tools/notices/cel-0.15.0.txt", root), "utf8"),
    );
  }
  if (!texts.length) throw new Error("Missing license text for Cargo dependency " + id);
  notices.set(
    label,
    "https://crates.io/crates/" + label.replace("@", "/") + "\n\n" + texts.join("\n"),
  );
}
if (!notices.size) throw new Error("No target library artifacts found for the Wasm parser");
mkdirSync(out, { recursive: true });
const version = execFileSync("rustc", ["--version"], { encoding: "utf8" }).trim();
const sysroot = execFileSync("rustc", ["--print", "sysroot"], { encoding: "utf8" }).trim();
copyFileSync(
  join(sysroot, "share/doc/rust/COPYRIGHT-library.html"),
  join(out, "rust-standard-library.html"),
);
const binaryen = new URL("./", import.meta.resolve("binaryen"));
const compiler = JSON.parse(readFileSync(new URL("package.json", binaryen), "utf8"));
copyFileSync(new URL("LICENSE", binaryen), join(out, "binaryen.txt"));
const summary = [
  "The packaged FASTA/HELM parser and the standalone Rust oligo measurement use " + version + ".",
  "The standard library's copyright notices are in rust-standard-library.html.",
  "The oligo measurement uses the standard library only. Its JavaScript is generated by Binaryen " +
    compiler.version +
    " (binaryen.txt).",
  "Cargo compiled the following registry libraries for the " + target + " parser.",
  ...[...notices.keys()].sort().map((label) => label + "\n" + notices.get(label)),
];
writeFileSync(join(out, "rust-wasm.txt"), summary.join("\n\n") + "\n");
