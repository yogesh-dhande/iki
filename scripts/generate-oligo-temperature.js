// Build the DNA worker's module and its synchronous browser translation (ADR 0191).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";

const wasmDir = fileURLToPath(new URL("../web/packages/science/wasm/", import.meta.url));
const digestFile = new URL("../plugins/dna/data/oligo-measurement.sha256", import.meta.url);
const generated = new URL(
  "../web/packages/science/generated/oligo-temperature.js",
  import.meta.url,
);
const checking = process.argv.includes("--check");
const canonicalHost = process.platform === "linux" && process.arch === "x64";

function copyCanonicalModule(binary) {
  const buildImage = fileURLToPath(new URL("./build-wasm-image.sh", import.meta.url));
  const image = execFileSync(buildImage, { encoding: "utf8" }).trim();
  const container = execFileSync("docker", ["create", "--platform", "linux/amd64", image], {
    encoding: "utf8",
  }).trim();
  try {
    execFileSync("docker", ["cp", container + ":/src/worker/oligo-measurement.wasm", binary]);
  } finally {
    execFileSync("docker", ["rm", container]);
  }
}

function translate(binary) {
  const compiler = fileURLToPath(import.meta.resolve("binaryen/bin/wasm2js"));
  // --emscripten emits the factory without instantiating it at import time.
  const module = execFileSync(
    process.execPath,
    [compiler, "-Oz", "--all-features", "--emscripten", binary],
    {
      encoding: "utf8",
    },
  );
  return (
    "// Generated by pnpm generate:temperature from the DNA plugin’s Rust/Wasm measurement.\n" +
    module
      .trimEnd()
      .split("\n")
      .map((line) => line.trimEnd())
      .join("\n") +
    "\n\nexport { instantiate };\n"
  );
}

mkdirSync(wasmDir, { recursive: true });
const temporary = mkdtempSync(join(wasmDir, ".temperature-"));
const binary = join(temporary, "oligo-measurement.wasm");
try {
  if (checking) {
    const compile = fileURLToPath(new URL("./build-oligo-wasm.sh", import.meta.url));
    execFileSync(compile, [binary], { stdio: "inherit" });
  } else {
    copyCanonicalModule(binary);
  }
  const bytes = readFileSync(binary);
  if (!globalThis.WebAssembly.validate(bytes))
    throw new Error("Expected the built DNA measurement module.");

  if (checking) {
    const recorded = readFileSync(digestFile, "utf8");
    if (!/^[a-f0-9]{64}\n$/.test(recorded))
      throw new Error("Expected the recorded DNA measurement SHA-256.");
    const source = readFileSync(generated, "utf8");
    if (!source) throw new Error("Expected the generated browser temperature measurement.");
    if (canonicalHost) {
      const digest = createHash("sha256").update(bytes).digest("hex") + "\n";
      if (recorded !== digest) {
        throw new Error("The DNA measurement digest is stale. Run pnpm generate:temperature.");
      }
      if (source !== translate(binary)) {
        throw new Error(
          "The browser temperature measurement is stale. Run pnpm generate:temperature.",
        );
      }
    } else {
      process.stdout.write(
        `Built the native measurement on ${process.platform}/${process.arch}. Skipping native digest and generated-JavaScript byte comparisons because the release compiler host is linux/x64. The package tests compare the measurement results.\n`,
      );
    }
  } else {
    const source = translate(binary);
    writeFileSync(generated, source);
    writeFileSync(digestFile, createHash("sha256").update(bytes).digest("hex") + "\n");
  }
  // The parity test instantiates the complete module produced by this invocation.
  renameSync(binary, join(wasmDir, "oligo-measurement.wasm"));
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
