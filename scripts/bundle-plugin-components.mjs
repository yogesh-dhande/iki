// ADRs 0084 and 0191. Each sandbox can load exactly one integrity-checked module.
import { readFile, writeFile } from "node:fs/promises";
import { relative, resolve } from "node:path";
import process from "node:process";
import { rolldown } from "rolldown";

const root = resolve(import.meta.dirname, "..");
const components = [
  "example_lims/booking-calendar",
  "oligo/chemistry",
  "oligo/duplex",
  "complex/composition",
  "plasmid/plasmid-map",
];

for (const component of components) {
  const [plugin, name] = component.split("/");
  const base = resolve(root, "plugins", plugin);
  const input = resolve(base, "web/src", name + ".js");
  const file = resolve(base, "components", name + ".js");
  const bundle = await rolldown({
    cwd: root,
    input,
    platform: "browser",
    resolve: { conditionNames: ["@ikisci/source", "import", "browser", "default"] },
  });
  try {
    const { output } = await bundle.generate({
      format: "esm",
      banner:
        "// Generated by pnpm bundle:plugins. Edit " + relative(root, input) + " and its imports.",
    });
    const [chunk] = output;
    if (
      output.length !== 1 ||
      chunk.type !== "chunk" ||
      chunk.imports.length ||
      chunk.dynamicImports.length
    ) {
      throw new Error(component + " must run in one self-contained module");
    }
    if (process.argv.includes("--check")) {
      if (chunk.code !== (await readFile(file, "utf8"))) {
        throw new Error(relative(root, file) + " is out of date. Run pnpm bundle:plugins.");
      }
    } else {
      await writeFile(file, chunk.code);
    }
  } finally {
    await bundle.close();
  }
}
