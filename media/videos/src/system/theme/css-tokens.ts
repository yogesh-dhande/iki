// Reads the light theme's custom properties from Iki's stylesheet, the source of the web
// app's design tokens. Used to generate tokens.generated.ts and to test that it hasn't drifted.

/** Where the web app's design tokens live, relative to this package. */
export const TOKENS_CSS = "../../server/src/iki_server/web/static/iki/iki.css";

/**
 * Every custom property set in a top-level `:root` block: the light theme. Blocks inside
 * `@media` (the dark theme) are skipped.
 */
export function lightTokens(css: string): Record<string, string> {
  const tokens: Record<string, string> = {};
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, "");
  let depth = 0;
  let index = 0;
  while (index < withoutComments.length) {
    const char = withoutComments[index];
    if (char === "{") depth += 1;
    else if (char === "}") depth -= 1;
    else if (depth === 0 && withoutComments.startsWith(":root", index)) {
      const open = withoutComments.indexOf("{", index);
      const close = withoutComments.indexOf("}", open);
      const body = withoutComments.slice(open + 1, close);
      for (const match of body.matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/g)) {
        const [, name, value] = match;
        if (name !== undefined && value !== undefined) tokens[name] = value.trim();
      }
      index = close + 1;
      continue;
    }
    index += 1;
  }
  return tokens;
}

/** tokens.generated.ts's source, for these tokens. */
export function tokensModule(tokens: Record<string, string>): string {
  const lines = Object.entries(tokens).map(
    ([name, value]) => `  ${JSON.stringify(name)}: ${JSON.stringify(value)},`,
  );
  return [
    "// Generated by `pnpm --filter @ikisci/videos tokens` from the web app's design tokens",
    "// (server/src/iki_server/web/static/iki/iki.css, light theme). Don't edit: regenerate.",
    "export const cssTokens = {",
    ...lines,
    "} as const;",
    "",
  ].join("\n");
}
