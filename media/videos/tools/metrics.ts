// Regenerates src/system/theme/metrics.generated.ts: each character's advance in the bundled
// text faces, measured by the renderer's own Chromium, so layouts can size things to their
// text without a browser (and tests can check them). Run it in the render image after
// changing a font:
//   media/videos/tools/container.sh node tools/metrics.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fontFaces } from "../src/system/theme/fonts.ts";
import { fontFamily, weight } from "../src/system/theme/theme.ts";
import { launch } from "./lib.ts";

const root = join(import.meta.dirname, "..");
/** Printable ASCII, and the typography scripts use. */
const characters = [
  ...Array.from({ length: 0x7f - 0x20 }, (_, i) => String.fromCharCode(0x20 + i)),
  ...[
    "’",
    "‘",
    "“",
    "”",
    "–",
    "—",
    "×",
    "′",
    "″",
    "‑",
    "µ",
    "α",
    "β",
    "γ",
    "δ",
    "ε",
    "κ",
    "λ",
    "μ",
    "°",
    "±",
    "≥",
    "≤",
    "→",
    "…",
    "·",
  ],
];
const faces = { regular: weight.regular, semibold: weight.semibold } as const;
/** Measured at this size and stored per em, rounded up, so sums never come out short. */
const EM = 1000;

const browser = await launch();
const page = await browser.newPage();
const sources = fontFaces
  .filter((face) => face.family === fontFamily.text)
  .map((face) => ({
    weight: face.weight,
    data: readFileSync(join(root, "fonts", face.file)).toString("base64"),
  }));
const measured = await page.evaluate(
  async ({ sources, characters, faces, family, em }) => {
    for (const source of sources) {
      const face = new FontFace(family, `url(data:font/woff2;base64,${source.data})`, {
        weight: String(source.weight),
      });
      document.fonts.add(await face.load());
    }
    const context = document.createElement("canvas").getContext("2d");
    if (!context) throw new Error("No 2D canvas.");
    const result: Record<string, Record<string, number>> = {};
    for (const [name, w] of Object.entries(faces)) {
      context.font = `${String(w)} ${String(em)}px "${family}"`;
      result[name] = Object.fromEntries(
        characters.map((c) => [c, Math.ceil(context.measureText(c).width)]),
      );
    }
    return result;
  },
  { sources, characters, faces, family: fontFamily.text, em: EM },
);
await browser.close();

const lines = [
  "// Generated by tools/metrics.ts from the bundled fonts: don't edit by hand.",
  "// Each character's advance, in thousandths of an em, as the renderer's Chromium draws it.",
  "",
  "export const advances = {",
  ...Object.entries(measured).map(
    ([name, table]) =>
      `  ${name}: {\n${Object.entries(table)
        .map(([c, width]) => `    ${JSON.stringify(c)}: ${String(width)},`)
        .join("\n")}\n  },`,
  ),
  "} as const;",
  "",
];
writeFileSync(join(root, "src/system/theme/metrics.generated.ts"), lines.join("\n"));
console.log("Wrote src/system/theme/metrics.generated.ts.");
