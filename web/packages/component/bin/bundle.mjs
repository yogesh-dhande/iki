// Bundles a plugin's components (ADR 0084, ADR 0286): each module in the plugin's
// `web/src/`, with everything it imports, into the one self-contained file its manifest's
// `module` names, `components/<name>.js`. A sandboxed frame loads exactly one
// integrity-checked module, so a bundle that would import anything else at run time is
// refused. With `check` it writes nothing, and fails if a bundle isn't what its source
// builds, for a plugin's CI. `iki-component-bundle` runs it from the command line.
//
// It needs rolldown, which this package names as an optional peer dependency.
import { readFile, readdir, writeFile } from "node:fs/promises";
import { basename, extname, relative, resolve } from "node:path";
import process from "node:process";

/** The modules a plugin's components are built from: each file directly in `web/src/`,
 * whose name is its component module's. Helpers they import go in subdirectories. */
export async function sources(plugin) {
  const directory = resolve(plugin, "web/src");
  let names;
  try {
    names = await readdir(directory, { withFileTypes: true });
  } catch {
    return [];
  }
  return names
    .filter((e) => e.isFile() && [".js", ".ts"].includes(extname(e.name)))
    .map((e) => resolve(directory, e.name))
    .sort();
}

/** Bundles each of `plugins`' components; with `check`, compares instead of writing.
 * `conditions` come first when resolving packages' exports. Returns the files it wrote,
 * or checked. */
export async function bundle(
  plugins,
  { check = false, conditions = [], root = process.cwd() } = {},
) {
  const { rolldown } = await import("rolldown");
  const done = [];
  for (const plugin of plugins) {
    const inputs = await sources(plugin);
    if (!inputs.length)
      throw new Error(`${relative(root, plugin) || "."} has no web/src/ to bundle`);
    for (const input of inputs) {
      const name = basename(input, extname(input));
      const file = resolve(plugin, "components", name + ".js");
      const built = await rolldown({
        cwd: root,
        input,
        platform: "browser",
        resolve: { conditionNames: [...conditions, "import", "browser", "default"] },
      });
      try {
        const { output } = await built.generate({
          format: "esm",
          banner: `// Generated by iki-component-bundle. Edit ${relative(root, input)} and its imports.`,
        });
        const [chunk] = output;
        if (
          output.length !== 1 ||
          chunk.type !== "chunk" ||
          chunk.imports.length ||
          chunk.dynamicImports.length
        ) {
          throw new Error(`${relative(root, input)} must bundle into one self-contained module`);
        }
        if (check) {
          let current = null;
          try {
            current = await readFile(file, "utf8");
          } catch {
            // Not built yet: out of date.
          }
          if (chunk.code !== current) {
            throw new Error(`${relative(root, file)} is out of date. Run iki-component-bundle.`);
          }
        } else {
          await writeFile(file, chunk.code);
        }
        done.push(file);
      } finally {
        await built.close();
      }
    }
  }
  return done;
}
