// Builds the small_molecule plugin's depiction component (../components/depiction.js)
// from src/depiction.js and RDKit.js, the @rdkit/rdkit package this one pins, into one
// module, as Iki's component frames need (ADR 0084): RDKit.js's loader, made to run
// without evaluating code (no-eval.js says how), then its WebAssembly, gzipped and in
// base64, then the component.
//
// `node build.js --check` (this package's test, which `make check` runs) fails if the
// committed module isn't what the pinned package and the source make.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync, gzipSync } from "node:zlib";

import { withoutEval } from "./no-eval.js";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
// The package exports its loader (dist/RDKit_minimal.js), not its package.json.
const pkg = dirname(dirname(require.resolve("@rdkit/rdkit")));
const { version, license } = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8"));
const loader = readFileSync(join(pkg, "dist", "RDKit_minimal.js"), "utf8");
const wasm = readFileSync(join(pkg, "dist", "RDKit_minimal.wasm"));
const component = readFileSync(join(here, "src", "depiction.js"), "utf8");
const target = join(here, "..", "components", "depiction.js");

const sha256 = (data) => createHash("sha256").update(data).digest("hex");

/** The module, with the WebAssembly packed as given. */
const build = (packed) =>
  [
    "// GENERATED by plugins/small_molecule/web/build.js: edit web/src/depiction.js, then",
    "// run `pnpm --filter @ikisci/small-molecule-web bundle`.",
    "//",
    `// RDKit.js ${version} (@rdkit/rdkit), RDKit's MinimalLib built with Emscripten:`,
    `// ${license}, Copyright (c) 2006-2015, Rational Discovery LLC, Greg Landrum, and Julie`,
    "// Penzotti and others (https://github.com/rdkit/rdkit/blob/master/license.txt); its",
    "// Emscripten runtime MIT (https://github.com/emscripten-core/emscripten). Its",
    "// WebAssembly holds the InChI library 1.07.3 (MIT), CoordGen and RingDecomposerLib",
    "// (BSD-3-Clause), Boost (BSL-1.0), FreeType 2.13.3 (the FreeType License: portions of",
    "// this software are copyright The FreeType Project, https://freetype.org, all rights",
    "// reserved), zlib, and the Telex font (SIL OFL 1.1).",
    `// RDKit_minimal.js sha256 ${sha256(loader)}, with embind's and emval's invokers as`,
    "// closures (web/no-eval.js); RDKit_minimal.wasm sha256",
    `// ${sha256(wasm)}, unchanged.`,
    "",
    withoutEval(loader).trimEnd(),
    "",
    `const RDKIT_WASM_GZIP_BASE64 = "${packed}";`,
    "",
    component,
  ].join("\n");

const PACKED = /^const RDKIT_WASM_GZIP_BASE64 = "([A-Za-z0-9+/=]*)";$/m;

if (process.argv.includes("--check")) {
  // zlib's output can differ between Node's releases, so the WebAssembly is checked
  // by what it unpacks to, and the rest byte for byte.
  let committed = "";
  try {
    committed = readFileSync(target, "utf8");
  } catch {
    // Missing: out of date.
  }
  const packed = PACKED.exec(committed)?.[1] ?? "";
  let unpacked = Buffer.alloc(0);
  try {
    unpacked = gunzipSync(Buffer.from(packed, "base64"));
  } catch {
    // Not gzip: out of date.
  }
  if (committed !== build(packed) || !unpacked.equals(wasm)) {
    console.error(
      "plugins/small_molecule/components/depiction.js is out of date. Run: " +
        "pnpm --filter @ikisci/small-molecule-web bundle",
    );
    process.exit(1);
  }
  console.log(`The depiction component is up to date (RDKit.js ${version}).`);
} else {
  const built = build(gzipSync(wasm, { level: 9 }).toString("base64"));
  writeFileSync(target, built);
  console.log(
    `Wrote ${target}: ${(built.length / 1024 ** 2).toFixed(1)} MiB, RDKit.js ${version}.`,
  );
}
