"""Rust types for the worker protocol (ADR 0010), from the schemas the server uses.

``iki-protocol`` (in ``worker/``) holds serde types for:

- what a command reads and writes: the ``run-input/v1`` and ``run-output/v1`` JSON
  Schemas in ``spec/``
- the ``/worker/v1`` API: the components of its OpenAPI document, as committed beside
  the crate (``worker-openapi.json``), with a constant for each path

so the Rust worker and the Python server can't drift apart: CI regenerates them and
fails if they differ. Run ``make protocol`` after changing either.

The schemas use a small part of JSON Schema, and this covers that part: objects with
properties, maps (``additionalProperties``), arrays, string enums and consts, nullable
types (``["string", "null"]`` or ``anyOf`` with null), and ``$ref``. Anything else is a
``serde_json::Value``. Unknown fields are accepted, so a worker keeps working against a
newer server.
"""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from iki_spec import schemas

__all__ = ["generate", "main"]

HEADER = """\
// @generated by `iki_codegen.protocol` from spec/'s run-input and run-output schemas and
// worker-openapi.json. Don't edit it: run `make protocol`.
"""

_RESERVED = {"type", "match", "ref", "self", "use", "mod", "fn", "impl", "move", "loop"}


def _pascal(text: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", text)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def _ident(name: str) -> str:
    snake = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()
    snake = re.sub(r"[^a-z0-9_]", "_", snake)
    return f"r#{snake}" if snake in _RESERVED else snake


def _doc(text: str | None, indent: str = "") -> list[str]:
    if not text:
        return []
    return [f"{indent}/// {line}".rstrip() for line in text.strip().splitlines()]


@dataclass
class _Generator:
    #: type name → its Rust source
    types: dict[str, list[str]] = field(default_factory=dict)
    #: "$ref" → type name, for the document being read
    refs: dict[str, str] = field(default_factory=dict)

    def _claim(self, name: str) -> None:
        if name in self.types:
            raise ValueError(f"Two protocol types are called {name}.")
        self.types[name] = []

    # --- Types ---------------------------------------------------------------------------

    def rust(self, schema: dict[str, Any] | bool, name: str) -> tuple[str, bool]:
        """The Rust type for `schema` (making named types as needed), and whether it's
        nullable."""
        if not isinstance(schema, dict) or not schema:
            return "serde_json::Value", False
        if "$ref" in schema:
            return self.refs[schema["$ref"]], False
        if "anyOf" in schema or "oneOf" in schema:
            members: list[dict[str, Any]] = schema.get("anyOf") or schema["oneOf"]
            real = [m for m in members if m.get("type") != "null"]
            nullable = len(real) < len(members)
            if len(real) == 1:
                inner, _ = self.rust({**real[0], "description": schema.get("description")}, name)
                return inner, nullable
            return "serde_json::Value", nullable
        kinds = schema.get("type")
        nullable = False
        if isinstance(kinds, list):
            nullable = "null" in kinds
            real = [k for k in kinds if k != "null"]
            kinds = real[0] if len(real) == 1 else None
            if kinds is None:
                return "serde_json::Value", nullable
        description = schema.get("description")
        if "const" in schema and isinstance(schema["const"], str):
            return self._enum(name, [schema["const"]], description, closed=True), nullable
        if "enum" in schema and all(isinstance(v, str) for v in schema["enum"]):
            return self._enum(name, schema["enum"], description, closed=False), nullable
        if kinds == "object" or "properties" in schema:
            if schema.get("properties"):
                return self._struct(name, schema), nullable
            extra = schema.get("additionalProperties", True)
            if isinstance(extra, dict) and extra:
                value, value_nullable = self.rust(extra, f"{name}Value")
                value = f"Option<{value}>" if value_nullable else value
                return f"std::collections::BTreeMap<String, {value}>", nullable
            return "serde_json::Map<String, serde_json::Value>", nullable
        if kinds == "array":
            item, item_nullable = self.rust(schema.get("items", {}), f"{name}Item")
            item = f"Option<{item}>" if item_nullable else item
            return f"Vec<{item}>", nullable
        simple = {"string": "String", "integer": "i64", "number": "f64", "boolean": "bool"}
        return simple.get(kinds if isinstance(kinds, str) else "", "serde_json::Value"), nullable

    def _enum(self, name: str, values: list[str], description: str | None, *, closed: bool) -> str:
        """A string enum. Unless it's `closed` (a const, such as ``apiVersion``), values
        a newer server adds read as ``Unknown`` instead of failing the whole message."""
        self._claim(name)
        lines = [*_doc(description)]
        lines.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]")
        lines.append(f"pub enum {name} {{")
        for value in values:
            variant = _pascal(value) or "Empty"
            lines.append(f'    #[serde(rename = "{value}")]')
            lines.append(f"    {variant},")
        if not closed:
            lines.append("    /// A value this version of the protocol doesn't know.")
            lines.append("    #[serde(other)]")
            lines.append("    Unknown,")
        lines.append("}")
        self.types[name] = lines
        return name

    def _struct(self, name: str, schema: dict[str, Any]) -> str:
        self._claim(name)
        required = set(schema.get("required", ()))
        fields: list[str] = []
        for prop, sub in schema["properties"].items():
            rust, nullable = self.rust(sub, f"{name}{_pascal(prop)}")
            ident = _ident(prop)
            doc = _doc(sub.get("description") if isinstance(sub, dict) else None, "    ")
            fields.extend(doc)
            if ident.removeprefix("r#") != prop:
                fields.append(f'    #[serde(rename = "{prop}")]')
            if prop not in required:
                fields.append('    #[serde(default, skip_serializing_if = "Option::is_none")]')
                fields.append(f"    pub {ident}: Option<{rust}>,")
            elif nullable:
                fields.append(f"    pub {ident}: Option<{rust}>,")
            else:
                fields.append(f"    pub {ident}: {rust},")
        lines = [*_doc(schema.get("description"))]
        lines.append("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]")
        lines.append(f"pub struct {name} {{")
        lines.extend(fields)
        lines.append("}")
        self.types[name] = lines
        return name

    # --- Documents -----------------------------------------------------------------------

    def spec_schema(self, root: str, schema: dict[str, Any]) -> None:
        self.refs = {f"#/$defs/{d}": f"{root}{_pascal(d)}" for d in schema.get("$defs", {})}
        for definition, sub in schema.get("$defs", {}).items():
            self.rust(sub, f"{root}{_pascal(definition)}")
        self.rust(schema, root)

    def openapi(self, document: dict[str, Any]) -> None:
        components = document.get("components", {}).get("schemas", {})
        self.refs = {f"#/components/schemas/{n}": n for n in components}
        for name in sorted(components):
            self.rust(components[name], name)

    def render(self, paths: list[tuple[str, str]]) -> str:
        out = [HEADER, "use serde::{Deserialize, Serialize};", ""]
        for lines in self.types.values():
            out.extend(lines)
            out.append("")
        out.append("/// The `/worker/v1` paths, with `{placeholders}` for their parameters.")
        out.append("pub mod paths {")
        for const, path in paths:
            out.append(f"    /// `{path}`")
            out.append(f'    pub const {const}: &str = "{path}";')
        out.append("}")
        return "\n".join(out) + "\n"


#: Paths served outside the OpenAPI document, as async views that wait (ADR 0043). Both
#: take ``?wait=`` seconds. The lease answers a ``RunInput`` or 204; a job's watch takes
#: ``{"lease_token": …}`` and answers ``{"cancel_requested": bool}``.
_OTHER_PATHS = ("/worker/v1/lease", "/worker/v1/jobs/{job_id}/watch")


def _paths(document: dict[str, Any]) -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    for path in sorted({*document.get("paths", {}), *_OTHER_PATHS}):
        tail = path.removeprefix("/worker/v1/")
        words = [w for w in re.split(r"[/{}]+", tail) if w and not w.endswith("_id")]
        const = "_".join(words).upper() or "ROOT"
        found.append((const, path))
    names = [c for c, _ in found]
    if len(names) != len(set(names)):
        raise ValueError(f"Two /worker/v1 paths make the same constant: {names}")
    return found


def generate(openapi: dict[str, Any]) -> str:
    """The generated Rust module, from the worker OpenAPI document and spec's schemas."""
    gen = _Generator()
    gen.spec_schema("RunInput", schemas.load("run-input"))
    gen.spec_schema("RunOutput", schemas.load("run-output"))
    gen.openapi(openapi)
    return gen.render(_paths(openapi))


def main(argv: list[str] | None = None) -> int:
    """``python -m iki_codegen.protocol worker-openapi.json``: prints the module."""
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1:
        sys.stderr.write("Usage: python -m iki_codegen.protocol <worker-openapi.json>\n")
        return 2
    document = json.loads(Path(args[0]).read_text(encoding="utf-8"))
    sys.stdout.write(generate(document))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
