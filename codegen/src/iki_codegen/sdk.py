"""Python types for the ``ikisci`` SDK, from the REST API's OpenAPI document.

Each schema in ``/api/v1``'s document becomes a ``TypedDict``, and each named enum a
``Literal`` alias, in ``sdk/python/src/iki/schema.py``. The SDK's answers are plain
dicts, as the JSON is, so these cost nothing at run time: they're for editors and type
checkers. That matches the TypeScript SDK, whose types come from the same document.

CI regenerates them and fails if they differ from what's committed. Run ``make client``
after changing the API.

The schemas use a small part of JSON Schema, and this covers that part: objects with
properties, maps (``additionalProperties``), arrays, enums and consts, nullable types,
``anyOf`` and ``allOf`` of one ``$ref``. Anything else is ``Any``.
"""

from __future__ import annotations

import json
import keyword
import re
import sys
from pathlib import Path
from typing import Any

__all__ = ["generate", "main"]

HEADER = '''\
# @generated by `iki_codegen.sdk` from web/packages/sdk/openapi.json.
# Don't edit it: run `make client`.
"""The REST API's request and response bodies, as typed dictionaries.

What the SDK returns is the API's JSON, as plain dicts and lists. These types say
what's in them, for your editor and type checker::

    from iki.schema import EntityOut

    def name_of(entity: EntityOut) -> str:
        return entity["values"].get("name", entity["hrid"])
"""

from __future__ import annotations

from typing import Any, Literal, NotRequired, TypedDict


'''


def _name(schema_name: str) -> str:
    """A class name: ``Page_EntityOut_`` becomes ``PageEntityOut``."""
    name = re.sub(r"[^0-9A-Za-z]", "", schema_name)
    if not name or name[0].isdigit():
        name = "Schema" + name
    return name


def _identifier(key: str) -> bool:
    return key.isidentifier() and not keyword.iskeyword(key)


class _Generator:
    def __init__(self, schemas: dict[str, Any]) -> None:
        self.schemas = schemas
        self.names = {key: _name(key) for key in schemas}
        clashes = len(set(self.names.values())) != len(self.names)
        if clashes:
            raise ValueError("Two schemas have the same Python name.")

    def type_of(self, schema: Any) -> str:  # noqa: ANN401 - JSON Schema
        if not isinstance(schema, dict) or not schema:
            return "Any"
        if "$ref" in schema:
            return self.names[schema["$ref"].rsplit("/", 1)[-1]]
        if "const" in schema:
            return f"Literal[{schema['const']!r}]"
        if "enum" in schema:
            return "Literal[" + ", ".join(repr(v) for v in schema["enum"]) + "]"
        for combiner in ("anyOf", "oneOf"):
            if combiner in schema:
                return self._union([self.type_of(s) for s in schema[combiner]])
        if "allOf" in schema:
            parts = schema["allOf"]
            return self.type_of(parts[0]) if len(parts) == 1 else "Any"
        kind = schema.get("type")
        if isinstance(kind, list):
            return self._union([self.type_of({**schema, "type": k}) for k in kind])
        return self._simple(kind, schema)

    def _simple(self, kind: Any, schema: dict[str, Any]) -> str:  # noqa: ANN401
        match kind:
            case "string":
                return "str"
            case "integer":
                return "int"
            case "number":
                return "float"
            case "boolean":
                return "bool"
            case "null":
                return "None"
            case "array":
                return f"list[{self.type_of(schema.get('items'))}]"
            case "object":
                extra = schema.get("additionalProperties")
                if isinstance(extra, dict) and extra:
                    return f"dict[str, {self.type_of(extra)}]"
                return "dict[str, Any]"
        return "Any"

    @staticmethod
    def _union(types: list[str]) -> str:
        unique = list(dict.fromkeys(types))
        if "Any" in unique:
            return "Any"
        # None last, as people write it.
        unique.sort(key=lambda t: t == "None")
        return " | ".join(unique)

    def define(self, key: str) -> str:
        schema = self.schemas[key]
        name = self.names[key]
        doc = (schema.get("description") or "").strip()
        if "enum" in schema or "const" in schema or schema.get("type") != "object":
            lines = [f"{name} = {self.type_of(schema)}"]
            if doc:
                lines = [*(f"#: {line}".rstrip() for line in doc.splitlines()), *lines]
            return "\n".join(lines)
        properties: dict[str, Any] = schema.get("properties") or {}
        required = set(schema.get("required") or [])
        fields = []
        for prop, sub in properties.items():
            annotation = self.type_of(sub)
            if prop not in required:
                annotation = f"NotRequired[{annotation}]"
            fields.append((prop, annotation, (sub.get("description") or "").strip()))
        if all(_identifier(prop) for prop, _, _ in fields):
            return self._class(name, doc, fields)
        # A key such as `not` can't be a class attribute: the functional form, whose
        # annotations are evaluated, so they're quoted.
        body = "".join(f"\n        {prop!r}: {annotation!r}," for prop, annotation, _ in fields)
        lines = [f"{name} = TypedDict(\n    {name!r},\n    {{{body}\n    }},\n)"]
        if doc:
            lines = [*(f"#: {line}".rstrip() for line in doc.splitlines()), *lines]
        return "\n".join(lines)

    @staticmethod
    def _class(name: str, doc: str, fields: list[tuple[str, str, str]]) -> str:
        lines = [f"class {name}(TypedDict):"]
        if doc:
            text = doc.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
            lines += [f'    """{text}"""' if "\n" not in text else f'    """{text}\n    """']
        for prop, annotation, description in fields:
            lines += [f"    #: {line}".rstrip() for line in description.splitlines()]
            lines.append(f"    {prop}: {annotation}")
        if not fields and not doc:
            lines.append("    pass")
        return "\n".join(lines)


def generate(openapi: dict[str, Any]) -> str:
    """The source of ``iki/schema.py`` for an OpenAPI document."""
    schemas: dict[str, Any] = openapi.get("components", {}).get("schemas", {})
    generator = _Generator(schemas)
    definitions = [
        generator.define(key) for key in sorted(schemas, key=generator.names.__getitem__)
    ]
    exported = ", ".join(repr(generator.names[key]) for key in sorted(schemas, key=str.lower))
    return HEADER + "\n\n\n".join(definitions) + f"\n\n\n__all__ = [{exported}]\n"


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) != 1:
        sys.stderr.write("usage: python -m iki_codegen.sdk OPENAPI_JSON > schema.py\n")
        return 2
    sys.stdout.write(generate(json.loads(Path(args[0]).read_text())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
