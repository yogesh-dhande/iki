"""Renders a plugin's ``models.py``: one Django model per table Iki keeps for it.

For each entity type:

- its table, extending ``core.Entity`` (or its parent type) with multi-table
  inheritance, with a typed column per field and CHECK constraints for every
  rule the database can enforce;
- its history table, append-only, one row per revision, with every field the
  type ever had (removed fields included) and no constraints or foreign keys,
  so history survives whatever happens to what it pointed to;
- a table per list of references or files, one row per item, so each item has
  a real foreign key. Other lists are arrays.

Extensions get the same, keyed by the extended type's ``entity_id``.

Descriptions and units become table and column comments when the server
syncs its plugins at deploy time, not here: they are documentation, so
changing them needs no migration.

Output is deterministic: the same plugin always renders the same bytes.
"""

from __future__ import annotations

import datetime as dt
import math
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from typing import Any

from iki_spec import naming
from iki_spec.model import FORMATS, EntityType, Extension, Field, Plugin

__all__ = ["render_models"]

HEADER = '''\
"""Models for the {plugin} plugin, generated by `iki plugin build` from its manifests.

Don't edit this file: change the manifests, then run `iki plugin makemigrations`.
"""

# ruff: noqa
# fmt: off
import datetime

from django.contrib.postgres.fields import ArrayField
from django.db import models
from django.db.models import Q
from django.db.models.functions import Length
from django.db.models.lookups import GreaterThanOrEqual, LessThanOrEqual

from iki_server.entities import checks
from iki_server.entities.fields import QuantityField
from iki_server.entities.models import Entity
from iki_server.files.models import Blob
'''


def render_models(plugin: Plugin, types: Mapping[str, EntityType]) -> str:
    """``types`` holds every type the plugin can name, its dependencies' included."""
    out = [HEADER.format(plugin=plugin.name)]
    imports = sorted(
        {
            t.extends.split(".")[0]
            for t in plugin.types.values()
            if t.extends and t.extends.split(".")[0] not in (plugin.name, "core")
        }
    )
    if imports:
        out.append("\n" + "".join(f"import {naming.package(name)}.models\n" for name in imports))
    for entity_type in _in_order(plugin):
        out.extend(_type(entity_type, plugin))
    for extension in sorted(plugin.extensions, key=lambda e: e.extends_type):
        out.extend(_extension(extension, types))
    return "".join(out).rstrip() + "\n"


def _in_order(plugin: Plugin) -> list[EntityType]:
    """Parents before subtypes (Python needs the class first), else by name."""
    done: dict[str, EntityType] = {}

    def visit(t: EntityType) -> None:
        if t.qualified_name in done:
            return
        if t.extends in plugin.types:
            visit(plugin.types[t.extends])
        done[t.qualified_name] = t

    for name in sorted(plugin.types):
        visit(plugin.types[name])
    return list(done.values())


# --- Models ------------------------------------------------------------------------------------


@dataclass
class _Model:
    name: str
    base: str
    doc: str
    table: str
    attributes: list[str] = field(default_factory=list)
    fields: list[tuple[str, str]] = field(default_factory=list)
    constraints: list[str] = field(default_factory=list)

    def render(self) -> str:
        lines = [f"\n\nclass {self.name}({self.base}):", f"    {_docstring(self.doc)}", ""]
        lines += [f"    {line}" for line in self.attributes]
        if self.attributes:
            lines.append("")
        lines += [f"    {name} = {_wrap(spec, 4, len(name) + 3)}" for name, spec in self.fields]
        if self.fields:
            lines.append("")
        lines += [
            "    class Meta:",
            f"        db_table = {self.table!r}",
        ]
        if self.constraints:
            lines.append("        constraints = [")
            lines += [f"            {_wrap(c, 12, 0, 1)}," for c in self.constraints]
            lines.append("        ]")
        return "\n".join(lines) + "\n"


def _type(t: EntityType, plugin: Plugin) -> list[str]:
    if t.extends is None or t.extends == "core.Entity":
        base, link_name, link_to = "Entity", "entity", "Entity"
    else:
        base = _class_ref(t.extends, plugin.name)
        link_name, link_to = naming.parent_link(t.extends), base
    description = f" {t.description}" if t.description else ""
    model = _Model(
        name=t.name,
        base=base,
        doc=f"{t.label} ({t.qualified_name}), schema version {t.schema_version}.{description}",
        table=t.table,
        attributes=[f"IKI_TYPE = {t.qualified_name!r}"],
    )
    model.fields.append(
        (
            link_name,
            _call(
                "models.OneToOneField",
                _raw(link_to),
                _raw("models.PROTECT"),
                parent_link=True,
                primary_key=True,
                db_column="entity_id",
                # No accessor from the parent: it would carry the type's name, so renaming
                # the type would look to Django like a new model.
                related_name="+",
            ),
        )
    )
    return _with_fields(model, t.qualified_name, t.fields, plugin.name)


def _extension(e: Extension, types: Mapping[str, EntityType]) -> list[str]:
    target = types.get(e.extends_type)
    label = target.label if target else e.extends_type
    description = f" {e.description}" if e.description else ""
    model = _Model(
        name=naming.extension_model(e.extends_type),
        base="models.Model",
        doc=f"The fields the {e.plugin} plugin adds to {label} ({e.extends_type}).{description}",
        table=e.table,
        attributes=[f"IKI_EXTENDS = {e.extends_type!r}"],
    )
    model.fields.append(
        (
            "entity",
            _call(
                "models.OneToOneField",
                e.extends_type,
                _raw("models.PROTECT"),
                primary_key=True,
                db_column="entity_id",
                related_name=naming.extension_related_name(e.plugin),
            ),
        )
    )
    return _with_fields(model, e.extends_type, e.fields, e.plugin)


def _with_fields(model: _Model, owner: str, fields: dict[str, Field], plugin: str) -> list[str]:
    """The model with its current fields, then its history model and list models."""
    lists: list[_Model] = []
    for f in fields.values():
        if f.removed:
            continue
        if _is_list_table(f):
            lists.append(_list_model(model, owner, f, plugin))
            continue
        model.fields.append((f.name, _column(f, plugin)))
        model.constraints.extend(_checks(model.table, f))
    history = _Model(
        name=naming.history_model(model.name),
        base="models.Model",
        doc=f"The history of {model.table}: its values at each revision of each entity.",
        table=naming.history_table(model.table),
        attributes=[f"IKI_HISTORY_OF = {model.name!r}", "APPEND_ONLY = True"],
        fields=[
            ("pk", _call("models.CompositePrimaryKey", "entity_id", "revision")),
            ("entity_id", _call("models.UUIDField")),
            ("revision", _call("models.PositiveIntegerField")),
        ],
    )
    history.fields += [(f.name, _history_column(f)) for f in fields.values()]
    return [m.render() for m in (model, history, *lists)]


def _list_model(owner: _Model, owner_type: str, f: Field, plugin: str) -> _Model:
    assert f.items is not None  # noqa: S101 - lists have items
    table = naming.list_table(owner.table, f.name)
    model = _Model(
        name=naming.list_model(owner.name, f.name),
        base="models.Model",
        doc=f"The items of {owner_type}.{f.name}, in order.",
        table=table,
        attributes=[f"IKI_LIST_OF = {(owner.name, f.name)!r}"],
        fields=[
            ("pk", _call("models.CompositePrimaryKey", "entity", "position")),
            (
                "entity",
                _call(
                    "models.ForeignKey",
                    owner.name,
                    _raw("models.CASCADE"),
                    db_column="entity_id",
                    related_name="+",
                ),
            ),
            ("position", _call("models.PositiveIntegerField")),
            ("item", _column(f.items, plugin, required=True)),
        ],
    )
    if f.max_items is not None:
        model.constraints.append(
            _check(
                f"Q(position__lt={f.max_items})",
                naming.constraint_name(table, "position", "max_items"),
            )
        )
    return model


# --- Columns -----------------------------------------------------------------------------------


def _is_list_table(f: Field) -> bool:
    return f.type == "list" and f.items is not None and f.items.type in ("ref", "file")


def _column(
    f: Field,
    plugin: str,
    *,
    required: bool | None = None,
    item: bool = False,
) -> str:
    """The Django field for a column holding ``f``'s values."""
    options: dict[str, Any] = {}
    if not item:
        if not (f.required if required is None else required):
            options["null"] = True
        if f.has_default:
            options["db_default"] = _raw(_value(f, f.default))
        if f.indexed and f.type not in ("ref",):
            options["db_index"] = True
    kind = f.type
    if kind == "string":
        if f.max_length is not None:
            return _call("models.CharField", max_length=f.max_length, **options)
        return _call("models.TextField", **options)
    if kind in ("text", "enum"):
        return _call("models.TextField", **options)
    if kind == "int":
        return _call("models.BigIntegerField", **options)
    if kind == "float":
        return _call("models.FloatField", **options)
    if kind == "quantity":
        return _call("QuantityField", unit=f.unit, **options)
    if kind == "bool":
        return _call("models.BooleanField", **options)
    if kind == "date":
        return _call("models.DateField", **options)
    if kind == "datetime":
        return _call("models.DateTimeField", **options)
    if kind == "json":
        return _call("models.JSONField", **options)
    if kind == "file":
        return _call(
            "models.ForeignKey", _raw("Blob"), _raw("models.PROTECT"), related_name="+", **options
        )
    if kind == "ref":
        assert f.to is not None  # noqa: S101 - refs have a target
        target = _raw("Entity") if f.to == "core.Entity" else _model_ref(f.to, plugin)
        return _call(
            "models.ForeignKey", target, _raw("models.PROTECT"), related_name="+", **options
        )
    if kind == "list":
        assert f.items is not None  # noqa: S101 - lists have items
        base = _column(f.items, plugin, item=True)
        return _call("ArrayField", _raw(base), **options)
    raise AssertionError(kind)  # pragma: no cover


def _history_column(f: Field) -> str:
    """History columns take any value the field ever allowed: wide types, no checks, no FKs."""
    options: dict[str, Any] = {"null": True}
    if f.type == "list":
        assert f.items is not None  # noqa: S101 - lists have items
        return _call("ArrayField", _raw(_history_type(f.items)), **options)
    return _history_type(f, **options)


_HISTORY_TYPES = {
    "string": "models.TextField",
    "text": "models.TextField",
    "enum": "models.TextField",
    "int": "models.BigIntegerField",
    "float": "models.FloatField",
    "bool": "models.BooleanField",
    "date": "models.DateField",
    "datetime": "models.DateTimeField",
    "json": "models.JSONField",
    "ref": "models.UUIDField",
    "file": "models.UUIDField",
}


def _history_type(f: Field, **options: Any) -> str:  # noqa: ANN401 - literals
    if f.type in ("ref", "file") and "null" in options:
        # The same column name as the live table's foreign key.
        options = {"db_column": f"{f.name}_id", **options}
    if f.type == "quantity":
        return _call("QuantityField", unit=f.unit, **options)
    return _call(_HISTORY_TYPES[f.type], **options)


# --- Checks ------------------------------------------------------------------------------------


def _checks(table: str, f: Field) -> list[str]:
    """CHECK constraints for every rule the database can enforce on ``f``'s column."""
    column = f.name
    rules: list[tuple[str, str]] = []
    kind = f.type
    if kind in ("string", "text"):
        rules += _text_rules(column, f, item=False)
    elif kind == "enum":
        rules.append(("values", f"Q({column}__in={list(f.values)!r})"))
    elif kind == "int":
        rules += _bounds(column, f)
    elif kind in ("float", "quantity"):
        rules.append(("finite", f"Q({column}__gt=float('-inf'), {column}__lt=float('inf'))"))
        rules += _bounds(column, f)
    elif kind == "list":
        assert f.items is not None  # noqa: S101 - lists have items
        rules.append(("plain_list", f"checks.IsPlainList({column!r})"))
        if f.min_items is not None and f.min_items > 0:
            rules.append(("min_items", f"Q({column}__len__gte={f.min_items})"))
        if f.max_items is not None:
            rules.append(("max_items", f"Q({column}__len__lte={f.max_items})"))
        rules += _item_rules(column, f.items)
    return [
        _check(condition, naming.constraint_name(table, column, rule)) for rule, condition in rules
    ]


def _text_rules(column: str, f: Field, *, item: bool) -> list[tuple[str, str]]:
    rules: list[tuple[str, str]] = []
    low = 1 if f.min_length is None else f.min_length
    high = f.max_length if f.type == "text" else None
    if item:
        if low > 0 or high is not None:
            rules.append(
                ("item_length", f"checks.AllLengthsBetween({column!r}, {low or None!r}, {high!r})")
            )
        if f.type == "string":
            rules.append(("item_one_line", f"checks.NoneMatch({column!r}, {r'[\r\n]'!r})"))
        if f.format:
            rules.append(("item_format", f"checks.AllMatch({column!r}, {FORMATS[f.format]!r})"))
        if f.pattern:
            rules.append(("item_pattern", f"checks.AllMatch({column!r}, {_anchored(f.pattern)!r})"))
        return rules
    if low > 0:
        name = "not_empty" if low == 1 else "min_length"
        rules.append((name, f"GreaterThanOrEqual(Length({column!r}), {low})"))
    if high is not None:
        rules.append(("max_length", f"LessThanOrEqual(Length({column!r}), {high})"))
    if f.type == "string":
        rules.append(("one_line", f"~Q({column}__regex={r'[\r\n]'!r})"))
    if f.format:
        rules.append(("format", f"Q({column}__regex={FORMATS[f.format]!r})"))
    if f.pattern:
        rules.append(("pattern", f"Q({column}__regex={_anchored(f.pattern)!r})"))
    return rules


def _item_rules(column: str, items: Field) -> list[tuple[str, str]]:
    kind = items.type
    if kind in ("string", "text"):
        return _text_rules(column, items, item=True)
    if kind == "enum":
        return [("item_values", f"Q({column}__contained_by={list(items.values)!r})")]
    if kind == "int" and (items.min is not None or items.max is not None):
        return [
            (
                "item_bounds",
                f"checks.AllBetweenInt({column!r}, {_num(items.min)}, {_num(items.max)})",
            )
        ]
    if kind in ("float", "quantity"):
        return [
            (
                "item_bounds",
                f"checks.AllBetweenFloat({column!r}, {_num(items.min)}, {_num(items.max)})",
            )
        ]
    return []


def _bounds(column: str, f: Field) -> list[tuple[str, str]]:
    rules = []
    if f.min is not None:
        rules.append(("min", f"Q({column}__gte={_num(f.min)})"))
    if f.max is not None:
        rules.append(("max", f"Q({column}__lte={_num(f.max)})"))
    return rules


def _anchored(pattern: str) -> str:
    """Python's fullmatch, for PostgreSQL's ``~`` (which finds a match anywhere)."""
    return f"^(?:{pattern})$"


def _check(condition: str, name: str) -> str:
    return f"models.CheckConstraint(condition={condition}, name={name!r})"


# --- Python source -----------------------------------------------------------------------------


class _raw(str):  # noqa: N801 - reads as a marker in calls
    """Source code, used as is rather than quoted."""

    __slots__ = ()


def _source(value: Any) -> str:  # noqa: ANN401 - any literal
    if isinstance(value, _raw):
        return str(value)
    return _num(value) if isinstance(value, float) else repr(value)


def _call(function: str, *args: Any, **kwargs: Any) -> str:  # noqa: ANN401 - literals
    parts = [_source(a) for a in args] + [f"{k}={_source(v)}" for k, v in kwargs.items()]
    return _raw(f"{function}({', '.join(parts)})")


def _num(value: float | None) -> str:
    if value is None:
        return "None"
    if math.isinf(value):
        return f"float({'inf' if value > 0 else '-inf'!r})"
    return repr(value)


def _value(f: Field, value: Any) -> str:  # noqa: ANN401 - manifest data is JSON-shaped
    """A default, as Python source for ``db_default``."""
    if f.type == "list":
        assert f.items is not None  # noqa: S101 - lists have items
        return "[" + ", ".join(_value(f.items, v) for v in value) + "]"
    if f.type == "date":
        day = dt.date.fromisoformat(value)
        return f"datetime.date({day.year}, {day.month}, {day.day})"
    if f.type in ("float", "quantity"):
        return _num(float(value))
    return repr(value)


def _wrap(source: str, indent: int, before: int = 0, after: int = 0, width: int = 100) -> str:
    """Splits a call's arguments over lines when it doesn't fit after ``before`` characters."""
    head, _, rest = source.partition("(")
    fits = indent + before + len(source) + after <= width
    if fits or not _is_call_head(head) or not source.endswith(")"):
        return source
    pad = " " * (indent + 4)
    lines = [f"{pad}{_wrap(a, indent + 4, 0, 1, width)},\n" for a in _split_arguments(rest[:-1])]
    return head + "(\n" + "".join(lines) + " " * indent + ")"


def _is_call_head(head: str) -> bool:
    """``models.Field`` or ``condition=Q``: something called, not text that has a bracket."""
    return bool(head) and all(c.isalnum() or c in "_.=~" for c in head)


def _split_arguments(text: str) -> Iterable[str]:
    depth, start, quote = 0, 0, ""
    i = 0
    while i < len(text):
        c = text[i]
        if quote:
            if c == "\\":
                i += 1
            elif c == quote:
                quote = ""
        elif c in "'\"":
            quote = c
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "," and depth == 0:
            yield text[start:i].strip()
            start = i + 1
        i += 1
    if text[start:].strip():
        yield text[start:].strip()


def _docstring(text: str) -> str:
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return f'"""{text}"""'


def _class_ref(qualified: str, plugin: str) -> str:
    owner, name = qualified.split(".")
    return name if owner == plugin else f"{naming.package(owner)}.models.{name}"


def _model_ref(qualified: str, plugin: str) -> str:
    owner, name = qualified.split(".")
    return name if owner == plugin else qualified
