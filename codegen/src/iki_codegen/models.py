#: What a model naming people imports, beside the header's.
PEOPLE_IMPORT = "from iki_server.accounts.models import User\n"


def render_models(plugin: Plugin, types: Mapping[str, EntityType]) -> str:
    """``types`` holds every type the plugin can name, its dependencies' included."""
    every = {**types, **plugin.types}
    header = HEADER.format(plugin=plugin.name)
    if _names_people(plugin):
        first = "from iki_server.entities import checks\n"
        header = header.replace(first, PEOPLE_IMPORT + first, 1)
    out = [header]
    imports = sorted(
        {
            t.extends.split(".")[0]
            for t in plugin.types.values()
            if t.extends and t.extends != naming.ENTITY and t.extends.split(".")[0] != plugin.name
        }
    )
    if imports:
        out.append("\n" + "".join(f"import {naming.package(name)}.models\n" for name in imports))
    for entity_type in _in_order(plugin):
        out.extend(_type(entity_type, plugin, every))
        if entity_type.identity:
            out.extend(_entry(entity_type, plugin, every))
        elif entity_type.extends and identity_owner(entity_type.extends, every) is not None:
            out.extend(_subtype_entry(entity_type, plugin, every))
    for extension in sorted(plugin.extensions, key=lambda e: e.extends_type):
        out.extend(_extension(extension, every))
    return "".join(out).rstrip() + "\n"


def _names_people(plugin: Plugin) -> bool:
    """Whether any of the plugin's tables has a field naming a person: a list's items and a
    row's fields (ADR 0137) included."""
    fields = [f for t in plugin.types.values() for f in t.fields.values()]
    fields += [f for e in plugin.extensions for f in e.fields.values()]
    return any(not f.removed and _holds_people(f) for f in fields)


def _holds_people(f: Field) -> bool:
    if f.type == "person":
        return True
    if f.items is None:
        return False
    return _holds_people(f.items) or any(_holds_people(c) for c in f.items.fields.values())


def _in_order(plugin: Plugin) -> list[EntityType]:
    """Parents before subtypes (Python needs the class first), else by name.

    ``iki/core.Entity`` is the server's own model (``iki_server.entities``), not a generated one.
    """
    done: dict[str, EntityType] = {}

    def visit(t: EntityType) -> None:
        if t.qualified_name in done:
            return
        if t.extends in plugin.types:
            visit(plugin.types[t.extends])
        done[t.qualified_name] = t

    for name in sorted(plugin.types):
        if name != naming.ENTITY:
            visit(plugin.types[name])
    return list(done.values())


# --- Models ------------------------------------------------------------------------------------


@dataclass
class _Model:
    name: str
    base: str
    doc: str
    table: str
    attributes: list[str] = field(default_factory=list)
    fields: list[tuple[str, str]] = field(default_factory=list)
    constraints: list[str] = field(default_factory=list)
    indexes: list[str] = field(default_factory=list)

    def render(self) -> str:
        lines = [f"\n\nclass {self.name}({self.base}):", f"    {_docstring(self.doc)}", ""]
        lines += [f"    {line}" for line in self.attributes]
        if self.attributes:
            lines.append("")
        lines += [f"    {name} = {_wrap(spec, 4, len(name) + 3)}" for name, spec in self.fields]
        if self.fields:
            lines.append("")
        lines += [
            "    class Meta:",
            f"        db_table = {self.table!r}",
        ]
        if self.constraints:
            lines.append("        constraints = [")
            lines += [f"            {_wrap(c, 12, 0, 1)}," for c in self.constraints]
            lines.append("        ]")
        if self.indexes:
            lines.append("        indexes = [")
            lines += [f"            {_wrap(i, 12, 0, 1)}," for i in self.indexes]
            lines.append("        ]")
        return "\n".join(lines) + "\n"


def _links(name: str, types: Mapping[str, EntityType]) -> list[str]:
    """The parent links along a type's ancestry, from the top down: its own last."""
    t = types.get(name)
    if t is None or t.extends is None or t.extends == naming.ENTITY:
        return []
    above = _links(t.extends, types)
    return [*above, naming.parent_link(t.extends, above)]


def _type(t: EntityType, plugin: Plugin, types: Mapping[str, EntityType]) -> list[str]:
    if t.extends is None or t.extends == naming.ENTITY:
        base, link_name, link_to = "Entity", "entity", "Entity"
    else:
        base = _class_ref(t.extends, plugin.name)
        link_name, link_to = _links(t.qualified_name, types)[-1], base
    description = f" {t.description}" if t.description else ""
    model = _Model(
        name=t.name,
        base=base,
        doc=f"{t.label} ({t.qualified_name}), schema version {t.schema_version}.{description}",
        table=t.table,
        attributes=[f"IKI_TYPE = {t.qualified_name!r}"],
    )
    model.fields.append(
        (
            link_name,
            _call(
                "models.OneToOneField",
                _raw(link_to),
                _raw("models.PROTECT"),
                parent_link=True,
                primary_key=True,
                db_column="entity_id",
                # No accessor from the parent: it would carry the type's name, so renaming
                # the type would look to Django like a new model.
                related_name="+",
            ),
        )
    )
    record, _ = split_entry(t.fields, t.identity)
    return _with_fields(model, t.qualified_name, record, plugin.name, types)


def _entry(t: EntityType, plugin: Plugin, types: Mapping[str, EntityType]) -> list[str]:
    """The table of a type's registry entries: its identity, derived and fact fields."""
    model = _Model(
        name=naming.entry_model(t.name),
        base="Entity",
        doc=f"Registry entries of {t.label} ({t.qualified_name}), ADR 0115.",
        table=naming.entry_table(t.table),
        attributes=[f"IKI_TYPE = {t.qualified_name!r}", "IKI_ENTRY = True"],
    )
    model.fields.append(
        (
            "entity",
            _call(
                "models.OneToOneField",
                _raw("Entity"),
                _raw("models.PROTECT"),
                parent_link=True,
                primary_key=True,
                db_column="entity_id",
                related_name="+",
            ),
        )
    )
    _, entry = split_entry(t.fields, t.identity)
    return _with_fields(model, t.qualified_name, entry, plugin.name, types)


def _subtype_entry(t: EntityType, plugin: Plugin, types: Mapping[str, EntityType]) -> list[str]:
    """The table of a subtype's registry entries (ADR 0165), under its parent's as its
    records' table is under theirs: the registry fields it adds. Every type under an
    identity has one, so an entry's tables follow its type's ancestry."""
    assert t.extends is not None  # noqa: S101 - only subtypes are under an identity
    base = _class_ref(_entry_name(t.extends), plugin.name)
    model = _Model(
        name=naming.entry_model(t.name),
        base=base,
        doc=f"Registry entries of {t.label} ({t.qualified_name}), ADR 0115: the registry "
        "fields it adds to its parent's (ADR 0165).",
        table=naming.entry_table(t.table),
        attributes=[f"IKI_TYPE = {t.qualified_name!r}", "IKI_ENTRY = True"],
    )
    model.fields.append(
        (
            naming.entry_parent_link(t.extends),
            _call(
                "models.OneToOneField",
                _raw(base),
                _raw("models.PROTECT"),
                parent_link=True,
                primary_key=True,
                db_column="entity_id",
                related_name="+",
            ),
        )
    )
    _, entry = split_entry(t.fields)
    return _with_fields(model, t.qualified_name, entry, plugin.name, types)


def _entry_name(qualified: str) -> str:
    """``iki/core.Complex``'s entries' model, qualified as a type is: ``iki/core.Complex_Entry``."""
    owner, name = qualified.split(".")
    return f"{owner}.{naming.entry_model(name)}"


def _extension(e: Extension, types: Mapping[str, EntityType]) -> list[str]:
    target = types.get(e.extends_type)
    label = target.label if target else e.extends_type
    description = f" {e.description}" if e.description else ""
    model = _Model(
        name=naming.extension_model(e.extends_type),
        base="models.Model",
        doc=f"The fields the {e.plugin} plugin adds to {label} ({e.extends_type}).{description}",
        table=e.table,
        attributes=[f"IKI_EXTENDS = {e.extends_type!r}"],
    )
    model.fields.append(
        (
            "entity",
            _call(
                "models.OneToOneField",
                naming.model_label(e.extends_type),
                _raw("models.PROTECT"),
                primary_key=True,
                db_column="entity_id",
                related_name=naming.extension_related_name(e.plugin),
            ),
        )
    )
    record, entry = split_entry(e.fields)
    owner = identity_owner(e.extends_type, types)
    # Registry fields alone need no table of the records'.
    out = (
        _with_fields(model, e.extends_type, record, e.plugin, types) if record or not entry else []
    )
    if entry and owner is not None:
        entries = _Model(
            name=naming.entry_model(model.name),
            base="models.Model",
            doc=f"The registry fields the {e.plugin} plugin adds to {label}'s entries "
            f"({e.extends_type}, ADR 0115).{description}",
            table=naming.entry_table(e.table),
            attributes=[f"IKI_EXTENDS = {e.extends_type!r}", "IKI_ENTRY = True"],
        )
        entries.fields.append(
            (
                "entity",
                _call(
                    "models.OneToOneField",
                    _entry_label(owner.qualified_name),
                    _raw("models.PROTECT"),
                    primary_key=True,
                    db_column="entity_id",
                    related_name=naming.entry_related_name(e.plugin),
                ),
            )
        )
        out += _with_fields(entries, e.extends_type, entry, e.plugin, types)
    return out


def identity_owner(qualified: str, types: Mapping[str, EntityType]) -> EntityType | None:
    """The type whose identity ``qualified``'s entities have: its own or a parent's."""
    if qualified not in types:
        return None
    owner = resolve_one(types, qualified).identity_owner
    return types[owner] if owner is not None else None


def _entry_label(qualified: str) -> str:
    """The model of a type's registry entries, as ``app_label.Model``."""
    return naming.entry_model(naming.model_label(qualified))


def _with_fields(
    model: _Model,
    owner: str,
    fields: dict[str, Field],
    plugin: str,
    types: Mapping[str, EntityType],
) -> list[str]:
    """The model with its current fields, then its history model and list models."""
    lists: list[_Model] = []
    for f in fields.values():
        if f.removed:
            continue
        if _is_list_table(f):
            lists.append(_list_model(model, owner, f, plugin, types))
            continue
        model.fields.append(
            (f.name, _state_column(f, fields) if f.type == "state" else _column(f, plugin, types))
        )
        model.constraints.extend(_checks(model.table, f))
        model.indexes.extend(_indexes(model.table, f))
    history = _Model(
        name=naming.history_model(model.name),
        base="models.Model",
        doc=f"The history of {model.table}: its values at each revision of each entity.",
        table=naming.history_table(model.table),
        attributes=[f"IKI_HISTORY_OF = {model.name!r}", "APPEND_ONLY = True"],
        fields=[
            ("pk", _call("models.CompositePrimaryKey", "entity_id", "revision")),
            ("entity_id", _call("models.UUIDField")),
            ("revision", _call("models.PositiveIntegerField")),
        ],
    )
    history.fields += [(f.name, _history_column(f)) for f in fields.values()]
    return [m.render() for m in (model, history, *lists)]


def _list_model(
    owner: _Model, owner_type: str, f: Field, plugin: str, types: Mapping[str, EntityType]
) -> _Model:
    assert f.items is not None  # noqa: S101 - lists have items
    table = naming.list_table(owner.table, f.name)
    model = _Model(
        name=naming.list_model(owner.name, f.name),
        base="models.Model",
        doc=f"The items of {owner_type}.{f.name}, in order.",
        table=table,
        attributes=[f"IKI_LIST_OF = {(owner.name, f.name)!r}"],
        fields=[
            ("pk", _call("models.CompositePrimaryKey", "entity", "position")),
            (
                "entity",
                _call(
                    "models.ForeignKey",
                    owner.name,
                    _raw("models.CASCADE"),
                    db_column="entity_id",
                    related_name="+",
                ),
            ),
            ("position", _call("models.PositiveIntegerField")),
        ],
    )
    if f.items.type == "row":
        # A row's fields are columns, checked as a type's are (ADR 0137).
        for cell in f.items.fields.values():
            model.fields.append((cell.name, _column(cell, plugin, types)))
            model.constraints.extend(_checks(table, cell))
    else:
        model.fields.append(("item", _column(f.items, plugin, types, required=True)))
    if f.max_items is not None:
        model.constraints.append(
            _check(
                f"Q(position__lt={f.max_items})",
                naming.constraint_name(table, "position", "max_items"),
            )
        )
    return model


# --- Columns -----------------------------------------------------------------------------------


def _is_list_table(f: Field) -> bool:
    return f.type == "list" and f.items is not None and f.items.type in LIST_TABLES


#: Lists of these get a table of their own.
LIST_TABLES = ("ref", "file", "person", "row")


def _column(
    f: Field,
    plugin: str,
    types: Mapping[str, EntityType],
    *,
    required: bool | None = None,
    item: bool = False,
) -> str:
    """The Django field for a column holding ``f``'s values."""
    options: dict[str, Any] = {}
    if not item:
        if not (f.required if required is None else required):
            options["null"] = True
        if f.has_default:
            options["db_default"] = _raw(_value(f, f.default))
        if f.indexed and f.type not in ("ref", "person"):
            options["db_index"] = True
    kind = f.type
    if kind == "string":
        if f.max_length is not None:
            return _call("models.CharField", max_length=f.max_length, **options)
        return _call("models.TextField", **options)
    if kind in ("text", "enum"):
        return _call("models.TextField", **options)
    if kind == "int":
        return _call("models.BigIntegerField", **options)
    if kind == "float":
        return _call("models.FloatField", **options)
    if kind == "quantity":
        return _call("QuantityField", unit=f.unit, **options)
    if kind == "bool":
        return _call("models.BooleanField", **options)
    if kind == "date":
        return _call("models.DateField", **options)
    if kind == "datetime":
        return _call("models.DateTimeField", **options)
    if kind == "json":
        return _call("models.JSONField", **options)
    if kind == "file":
        return _call(
            "models.ForeignKey", _raw("File"), _raw("models.PROTECT"), related_name="+", **options
        )
    if kind == "person":
        # People are deactivated, never deleted: PROTECT keeps that so.
        return _call(
            "models.ForeignKey", _raw("User"), _raw("models.PROTECT"), related_name="+", **options
        )
    if kind == "ref":
        assert f.to  # noqa: S101 - refs have a target
        target = _ref_target(f.to, plugin, types)
        return _call(
            "models.ForeignKey", target, _raw("models.PROTECT"), related_name="+", **options
        )
    if kind == "list":
        assert f.items is not None  # noqa: S101 - lists have items
        base = _column(f.items, plugin, types, item=True)
        return _call("ArrayField", _raw(base), **options)
    raise AssertionError(kind)  # pragma: no cover


def _state_column(f: Field, fields: Mapping[str, Field]) -> str:
    """A state field's column (ADR 0125): one of its states, the initial one to begin with.
    Its states are part of the column, so migrations see them change: records in a state
    the plugin removes move where it says (``moved``), as do a removed state field's
    records into this one (``moved_from``), and which lock decides who's locked."""
    live = list(f.live_states)
    options: dict[str, Any] = {"states": live}
    moved = {n: st.moved_to for n, st in f.states.items() if st.removed and st.moved_to}
    if moved:
        options["moved"] = dict(sorted(moved.items()))
    locking = [n for n in live if n in f.locking_states]
    if locking:
        options["locking"] = locking
    moved_from = {
        other.name: dict(other.moved_to.states)
        for other in fields.values()
        if other.removed and other.moved_to is not None and other.moved_to.field == f.name
    }
    if moved_from:
        options["moved_from"] = dict(sorted(moved_from.items()))
    if f.indexed:
        options["db_index"] = True
    return _call(
        "StateField",
        **options,
        db_default=f.initial,
        db_comment=f"A state field (ADR 0125): one of {', '.join(live)}.",
    )


def _ref_target(to: tuple[str, ...], plugin: str, types: Mapping[str, EntityType]) -> str:
    """What a reference to ``to`` is a foreign key to: the entries of a type with an
    identity, its own or a parent's (ADR 0165), ``iki_entity`` for an abstract type (whose
    subtypes may have entries or records), ``iki/core.Entity`` or several types (ADR 0136),
    else the type's own table of records. Where it's ``iki_entity``, ``sync_plugins`` puts a
    trigger on the table that holds the reference to its types."""
    if len(to) != 1:
        return _raw("Entity")
    target = types.get(to[0])
    if to[0] == naming.ENTITY or target is None or target.abstract:
        return _raw("Entity")
    if identity_owner(to[0], types) is not None:
        # Its own entries' table, which a subtype under an identity has too (ADR 0165).
        name = naming.entry_model(target.name)
        return name if target.plugin == plugin else _entry_label(target.qualified_name)
    return _model_ref(to[0], plugin)


def _indexes(table: str, f: Field) -> list[str]:
    """The GIN indexes a field gets for search: trigrams for indexed strings, so finding
    one that contains some text is fast; words for every searchable text field, for
    full-text search, since long text can't be indexed otherwise. Words are its first
    ``WORDS_SEARCHED`` characters', so the index always fits what Postgres keeps of them,
    and a long value always saves (ADR 0233); the server's search reads the same."""
    if f.type == "string" and f.indexed:
        return [
            _call(
                "GinIndex",
                fields=[f.name],
                opclasses=["gin_trgm_ops"],
                name=naming.index_name(table, f.name, "trgm"),
            )
        ]
    if f.type == "text" and f.searchable:
        return [
            _call(
                "GinIndex",
                _raw(f"SearchVector(Left({f.name!r}, {WORDS_SEARCHED}), config='simple')"),
                name=naming.index_name(table, f.name, "fts"),
            )
        ]
    return []


def _history_column(f: Field) -> str:
    """History columns take any value the field ever allowed: wide types, no checks, no FKs."""
    options: dict[str, Any] = {"null": True}
    if f.is_rows:
        # Each row an object of its fields' values, as the API gives them (ADR 0137).
        return _call("models.JSONField", **options)
    if f.type == "list":
        assert f.items is not None  # noqa: S101 - lists have items
        return _call("ArrayField", _raw(_history_type(f.items)), **options)
    return _history_type(f, **options)


_HISTORY_TYPES = {
    "string": "models.TextField",
    "text": "models.TextField",
    "enum": "models.TextField",
    "state": "models.TextField",
    "int": "models.BigIntegerField",
    "float": "models.FloatField",
    "bool": "models.BooleanField",
    "date": "models.DateField",
    "datetime": "models.DateTimeField",
    "json": "models.JSONField",
    "ref": "models.UUIDField",
    "file": "models.UUIDField",
    "person": "models.UUIDField",
}


def _history_type(f: Field, **options: Any) -> str:  # noqa: ANN401 - literals
    if f.type in ("ref", "file", "person") and "null" in options:
        # The same column name as the live table's foreign key.
        options = {"db_column": f"{f.name}_id", **options}
    if f.type == "quantity":
        return _call("QuantityField", unit=f.unit, **options)
    return _call(_HISTORY_TYPES[f.type], **options)


# --- Checks ------------------------------------------------------------------------------------


def _checks(table: str, f: Field) -> list[str]:
    """CHECK constraints for every rule the database can enforce on ``f``'s column."""
    column = f.name
    rules: list[tuple[str, str]] = []
    kind = f.type
    if kind in ("string", "text"):
        rules += _text_rules(column, f, item=False)
    elif kind == "enum":
        rules.append(("values", f"Q({column}__in={list(f.values)!r})"))
    elif kind == "state":
        rules.append(("known", f"Q({column}__in={list(f.live_states)!r})"))
    elif kind == "int":
        rules += _bounds(column, f)
    elif kind in ("float", "quantity"):
        rules.append(("finite", f"Q({column}__gt=float('-inf'), {column}__lt=float('inf'))"))
        rules += _bounds(column, f)
    elif kind == "list":
        assert f.items is not None  # noqa: S101 - lists have items
        rules.append(("plain_list", f"checks.IsPlainList({column!r})"))
        if f.min_items is not None and f.min_items > 0:
            rules.append(("min_items", f"Q({column}__len__gte={f.min_items})"))
        if f.max_items is not None:
            rules.append(("max_items", f"Q({column}__len__lte={f.max_items})"))
        rules += _item_rules(column, f.items)
    return [
        _check(condition, naming.constraint_name(table, column, rule)) for rule, condition in rules
    ]


def _text_rules(column: str, f: Field, *, item: bool) -> list[tuple[str, str]]:
    rules: list[tuple[str, str]] = []
    low = 1 if f.min_length is None else f.min_length
    high = f.max_length if f.type == "text" else None
    if item:
        if low > 0 or high is not None:
            rules.append(
                ("item_length", f"checks.AllLengthsBetween({column!r}, {low or None!r}, {high!r})")
            )
        if f.type == "string":
            rules.append(("item_one_line", f"checks.NoneMatch({column!r}, {r'[\r\n]'!r})"))
        if f.format:
            rules.append(("item_format", f"checks.AllMatch({column!r}, {FORMATS[f.format]!r})"))
        if f.pattern:
            rules.append(("item_pattern", f"checks.AllMatch({column!r}, {_anchored(f.pattern)!r})"))
        return rules
    if low > 0:
        name = "not_empty" if low == 1 else "min_length"
        rules.append((name, f"GreaterThanOrEqual(Length({column!r}), {low})"))
    if high is not None:
        rules.append(("max_length", f"LessThanOrEqual(Length({column!r}), {high})"))
    if f.type == "string":
        rules.append(("one_line", f"~Q({column}__regex={r'[\r\n]'!r})"))
    if f.format:
        rules.append(("format", f"Q({column}__regex={FORMATS[f.format]!r})"))
    if f.pattern:
        rules.append(("pattern", f"Q({column}__regex={_anchored(f.pattern)!r})"))
    return rules


def _item_rules(column: str, items: Field) -> list[tuple[str, str]]:
    kind = items.type
    if kind in ("string", "text"):
        return _text_rules(column, items, item=True)
    if kind == "enum":
        return [("item_values", f"Q({column}__contained_by={list(items.values)!r})")]
    if kind == "int" and (items.min is not None or items.max is not None):
        return [
            (
                "item_bounds",
                f"checks.AllBetweenInt({column!r}, {_num(items.min)}, {_num(items.max)})",
            )
        ]
    if kind in ("float", "quantity"):
        return [
            (
                "item_bounds",
                f"checks.AllBetweenFloat({column!r}, {_num(items.min)}, {_num(items.max)})",
            )
        ]
    return []


def _bounds(column: str, f: Field) -> list[tuple[str, str]]:
    rules = []
    if f.min is not None:
        rules.append(("min", f"Q({column}__gte={_num(f.min)})"))
    if f.max is not None:
        rules.append(("max", f"Q({column}__lte={_num(f.max)})"))
    return rules


def _anchored(pattern: str) -> str:
    """Python's fullmatch, for PostgreSQL's ``~`` (which finds a match anywhere)."""
    return f"^(?:{pattern})$"


def _check(condition: str, name: str) -> str:
    return f"models.CheckConstraint(condition={condition}, name={name!r})"


# --- Python source -----------------------------------------------------------------------------


class _raw(str):  # noqa: N801 - reads as a marker in calls
    """Source code, used as is rather than quoted."""

    __slots__ = ()


def _source(value: Any) -> str:  # noqa: ANN401 - any literal
    if isinstance(value, _raw):
        return str(value)
    return _num(value) if isinstance(value, float) else repr(value)


def _call(function: str, *args: Any, **kwargs: Any) -> str:  # noqa: ANN401 - literals
    parts = [_source(a) for a in args] + [f"{k}={_source(v)}" for k, v in kwargs.items()]
    return _raw(f"{function}({', '.join(parts)})")


def _num(value: float | None) -> str:
    if value is None:
        return "None"
    if math.isinf(value):
        return f"float({'inf' if value > 0 else '-inf'!r})"
    return repr(value)


def _value(f: Field, value: Any) -> str:  # noqa: ANN401 - manifest data is JSON-shaped
    """A default, as Python source for ``db_default``."""
    if f.type == "list":
        assert f.items is not None  # noqa: S101 - lists have items
        return "[" + ", ".join(_value(f.items, v) for v in value) + "]"
    if f.type == "date":
        day = dt.date.fromisoformat(value)
        return f"datetime.date({day.year}, {day.month}, {day.day})"
    if f.type in ("float", "quantity"):
        return _num(float(value))
    return repr(value)


def _wrap(source: str, indent: int, before: int = 0, after: int = 0, width: int = 100) -> str:
    """Splits a call's arguments over lines when it doesn't fit after ``before`` characters."""
    head, _, rest = source.partition("(")
    fits = indent + before + len(source) + after <= width
    if fits or not _is_call_head(head) or not source.endswith(")"):
        return source
    pad = " " * (indent + 4)
    lines = [f"{pad}{_wrap(a, indent + 4, 0, 1, width)},\n" for a in _split_arguments(rest[:-1])]
    return head + "(\n" + "".join(lines) + " " * indent + ")"


def _is_call_head(head: str) -> bool:
    """``models.Field`` or ``condition=Q``: something called, not text that has a bracket."""
    return bool(head) and all(c.isalnum() or c in "_.=~" for c in head)


def _split_arguments(text: str) -> Iterable[str]:
    depth, start, quote = 0, 0, ""
    i = 0
    while i < len(text):
        c = text[i]
        if quote:
            if c == "\\":
                i += 1
            elif c == quote:
                quote = ""
        elif c in "'\"":
            quote = c
        elif c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "," and depth == 0:
            yield text[start:i].strip()
            start = i + 1
        i += 1
    if text[start:].strip():
        yield text[start:].strip()


def _docstring(text: str) -> str:
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return f'"""{text}"""'


def _class_ref(qualified: str, plugin: str) -> str:
    owner, name = qualified.split(".")
    return name if owner == plugin else f"{naming.package(owner)}.models.{name}"


def _model_ref(qualified: str, plugin: str) -> str:
    owner, name = qualified.split(".")
    return name if owner == plugin else naming.model_label(qualified)
