"""Renders a plugin's ``models.py``: one Django model per table Iki keeps for it.

For each entity type:

- its table, extending ``iki/core.Entity`` (or its parent type) with multi-table
  inheritance, with a typed column per field and CHECK constraints for every
  rule the database can enforce;
- its history table, append-only, one row per revision, with every field the
  type ever had (removed fields included) and no constraints or foreign keys,
  so history survives whatever happens to what it pointed to;
- a table per list of references, files or people, one row per item, so each
  item has a real foreign key; and per list of rows (ADR 0137), a column per row
  field, each with its foreign key and checks. Other lists are arrays.

A field naming a person (ADR 0122) is a foreign key to ``iki_user``, which never
loses a row: people are deactivated, never deleted, so a record keeps whoever it
named.

Extensions get the same, keyed by the extended type's ``entity_id``.

A type with an identity has registry entries (ADR 0115): its identity fields, and
those marked ``registry: derived`` or ``registry: fact``, are in a table of its
entries (``<table>__entry``), whose rows are entities with a registry and no
project. The type's own table, of each project's records, has its other fields.
An extension's registry fields go in an entry table of its own beside its table.
A reference to a type with an identity holds an entry, so it's a foreign key to
the entries' table; one to an abstract type (``iki/core.Sequence``), which could
be either, is one to ``iki_entity``.

Descriptions and units become table and column comments when the server
syncs its plugins at deploy time, not here: they are documentation, so
changing them needs no migration.

Output is deterministic: the same plugin always renders the same bytes.
"""

