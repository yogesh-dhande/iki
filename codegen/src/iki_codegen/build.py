"""Writes the Django apps for a set of plugins, and the package that installs them.

For each plugin, a package ``iki_plugin_<name>``:

- ``apps.py``: the app, labelled with the plugin's name;
- ``models.py``: see :mod:`iki_codegen.models`;
- ``manifest.json``: the plugin as Iki read it, for the server, with the
  hosts its actions name through settings (``{settings.lims_host}``) filled
  in from the deployment's values;
- ``settings.json``: the deployment's values for its settings, when built
  for a deployment;
- ``migrations/``: the plugin repository's migrations, copied unchanged.

And ``iki_installed_plugins``, listing those apps in dependency order, with
the Iki version that built them (the server refuses a build by another) and,
for a deployment, ``lock.json``: where each plugin came from.

The same inputs always give the same bytes, so a build can be checked.
"""

from __future__ import annotations

import dataclasses
import json
import re
import shutil
from collections.abc import Mapping, Sequence
from importlib.metadata import version
from pathlib import Path
from typing import Any

from iki_codegen.models import render_models
from iki_spec import API_VERSION, naming
from iki_spec.model import BUILTIN_TYPES, EntityType, Plugin, plugin_to_dict

GENERATED = "Generated by `iki plugin build`. Don't edit it: change the plugin's manifests."


def in_dependency_order(plugins: Sequence[Plugin]) -> list[Plugin]:
    """Dependencies first, else by name. Raises ``ValueError`` naming a missing dependency."""
    by_name = {p.name: p for p in plugins}
    done: dict[str, Plugin] = {}

    def visit(plugin: Plugin, path: tuple[str, ...]) -> None:
        if plugin.name in done:
            return
        if plugin.name in path:
            raise ValueError(f"plugins depend on each other: {' → '.join([*path, plugin.name])}")
        for name in sorted(plugin.dependencies):
            if name not in by_name:
                raise ValueError(f"{plugin.name} needs the {name} plugin")
            visit(by_name[name], (*path, plugin.name))
        done[plugin.name] = plugin

    for plugin in sorted(plugins, key=lambda p: p.name):
        visit(plugin, ())
    return list(done.values())


def conflicts(plugins: Sequence[Plugin]) -> list[str]:
    """What plugins that each validate on their own can't do together in one deployment.

    Each plugin's validator only sees the plugins it depends on. Plugins that
    don't know each other can still share an HRID prefix, a table name, or
    a field they add to the same type.
    """
    problems = []
    prefixes: dict[str, str] = {}
    tables: dict[str, str] = {}
    added: dict[tuple[str, str], str] = {}
    for plugin in sorted(plugins, key=lambda p: p.name):
        for t in plugin.types.values():
            if t.hrid_prefix and not t.abstract:
                other = prefixes.setdefault(t.hrid_prefix, t.qualified_name)
                if other != t.qualified_name:
                    problems.append(
                        f"{other} and {t.qualified_name} both use the HRID prefix {t.hrid_prefix}"
                    )
            for table in (t.table, naming.history_table(t.table)):
                other = tables.setdefault(table, t.qualified_name)
                if other != t.qualified_name:
                    problems.append(f"{other} and {t.qualified_name} both need the table {table}")
        for e in plugin.extensions:
            for name in e.fields:
                key = (e.extends_type, name)
                other = added.setdefault(key, plugin.name)
                if other != plugin.name:
                    problems.append(
                        f"{other} and {plugin.name} both add the field `{name}` to {e.extends_type}"
                    )
    return problems


#: A host in an action's ``network`` that a setting gives.
SETTING_HOST = re.compile(r"\{settings\.([a-z][a-z0-9_]*)\}")


def with_hosts(plugin: Plugin, values: Mapping[str, Any]) -> Plugin:
    """`plugin` with each ``{settings.<name>}`` in its actions' ``network`` replaced by the
    host the deployment set. One left unset is dropped: its runs reach nothing there."""

    def hosts(network: tuple[str, ...]) -> tuple[str, ...]:
        out: list[str] = []
        for entry in network:
            match = SETTING_HOST.fullmatch(entry)
            host = values.get(match.group(1)) if match else entry
            if isinstance(host, str) and host and host not in out:
                out.append(host)
        return tuple(out)

    actions = {
        name: dataclasses.replace(action, network=hosts(action.network))
        for name, action in plugin.actions.items()
    }
    return dataclasses.replace(plugin, actions=actions)


def build(
    plugins: Sequence[Plugin],
    output: Path,
    *,
    migrations: Mapping[str, Path] | None = None,
    settings: Mapping[str, Mapping[str, Any]] | None = None,
    lock: Mapping[str, Any] | None = None,
    local: bool = False,
) -> list[Path]:
    """Writes the apps into ``output``, replacing earlier builds there. Returns the packages.

    ``migrations`` maps a plugin's name to its repository's ``migrations/``,
    and ``settings`` to the deployment's values for its settings. ``lock``
    records where the plugins came from; ``local`` says one came from a
    directory rather than a git commit, which only development servers accept.
    """
    ordered = in_dependency_order(plugins)
    problems = conflicts(ordered)
    if problems:
        raise ValueError("; ".join(problems))
    types: dict[str, EntityType] = dict(BUILTIN_TYPES)
    for plugin in ordered:
        types.update(plugin.types)
    output.mkdir(parents=True, exist_ok=True)
    # Plugins an earlier build here had and this one doesn't.
    wanted = {naming.package(p.name) for p in ordered}
    for stale in sorted(output.glob("iki_plugin_*")):
        if stale.is_dir() and stale.name not in wanted:
            shutil.rmtree(stale)
    packages = []
    for plugin in ordered:
        package = output / naming.package(plugin.name)
        if package.exists():
            shutil.rmtree(package)
        (package / "migrations").mkdir(parents=True)
        (package / "__init__.py").write_text(f'"""The {plugin.name} plugin. {GENERATED}"""\n')
        (package / "apps.py").write_text(_apps(plugin))
        (package / "models.py").write_text(render_models(plugin, types))
        given = settings.get(plugin.name) if settings is not None else None
        resolved = plugin if given is None else with_hosts(plugin, given)
        manifest = {"apiVersion": API_VERSION, "plugin": plugin_to_dict(resolved)}
        (package / "manifest.json").write_text(_json(manifest))
        if settings is not None and plugin.name in settings:
            (package / "settings.json").write_text(_json(dict(settings[plugin.name])))
        source = (migrations or {}).get(plugin.name)
        if source is not None and source.is_dir():
            for file in sorted(source.glob("*.py")):
                shutil.copyfile(file, package / "migrations" / file.name)
        (package / "migrations" / "__init__.py").touch()
        packages.append(package)
    registry = output / "iki_installed_plugins"
    if registry.exists():
        shutil.rmtree(registry)
    registry.mkdir()
    apps = "".join(f"    {naming.package(p.name) + '.apps.PluginConfig'!r},\n" for p in ordered)
    (registry / "__init__.py").write_text(
        f'"""The plugins this build installs, dependencies first. {GENERATED}"""\n\n'
        "#: The Iki that built them. A server of another version refuses to start.\n"
        f"IKI_VERSION = {version('iki-codegen')!r}\n"
        "#: Whether a plugin came from a local directory: only for development servers.\n"
        f"LOCAL = {local!r}\n\n"
        f"APPS = [\n{apps}]\n"
    )
    if lock is not None:
        (registry / "lock.json").write_text(_json(dict(lock)))
    return packages


def _json(data: Mapping[str, Any]) -> str:
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _apps(plugin: Plugin) -> str:
    title = plugin.title or plugin.name
    return (
        f'"""{GENERATED}"""\n\n'
        "from django.apps import AppConfig\n\n\n"
        "class PluginConfig(AppConfig):\n"
        f"    name = {naming.package(plugin.name)!r}\n"
        f"    label = {plugin.name!r}\n"
        f"    verbose_name = {title!r}\n"
        "    default_auto_field = 'django.db.models.BigAutoField'\n"
        f"    iki_version = {plugin.version!r}\n"
    )
